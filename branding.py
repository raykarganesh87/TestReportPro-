def custom_path():
    return os.path.join(core.DATA_DIR, 'logo.png')


def logo_bytes():
    p = custom_path()
    if os.path.exists(p):
        try:
            return open(p, 'rb').read()
        except OSError:
            pass
    return base64.b64decode(LOGO_B64)


def is_custom():
    return os.path.exists(custom_path())


def set_custom(src):
    """Accepts PNG / JPG / BMP / GIF; stored as PNG (max 800 px)."""
    from PIL import Image
    im = Image.open(src)
    im.thumbnail((800, 800))
    if im.mode not in ('RGB', 'RGBA'):
        im = im.convert('RGBA')
    os.makedirs(core.DATA_DIR, exist_ok=True)
    im.save(custom_path(), 'PNG')


def reset_custom():
    if os.path.exists(custom_path()):
        os.remove(custom_path())


def tk_photo(tk, max_h=56):
    """PhotoImage scaled to about max_h pixels high (works with plain Tk, no ImageTk needed)."""
    img = tk.PhotoImage(data=base64.b64encode(logo_bytes()))
    h = img.height()
    if h > max_h:
        img = img.subsample(max(1, round(h / max_h)))
    return img
